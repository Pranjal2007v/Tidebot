import threading
import time

from tidebot.ai import AIError
from tidebot.github import GitHubError
from tidebot.review import (ChangedFile, FileReview, Hunk, Suggestion, check, hunks, numbered,
                            parse_findings, pick_files, review_file, review_files,
                            skip_reason, verify, write_memo)

PATCH = "@@ -1,2 +1,3 @@\n import os\n+import sys\n x = 1"


def changed(path, status="modified", patch=PATCH):
    return ChangedFile(path, status, patch)


def test_from_api_reads_the_github_entry():
    f = ChangedFile.from_api({"filename": "a.py", "status": "added", "patch": PATCH})
    assert f == ChangedFile("a.py", "added", PATCH)
    assert ChangedFile.from_api({"filename": "logo.png"}).patch == ""


def test_lockfiles_and_generated_code_are_skipped():
    assert skip_reason(changed("app/main.py")) is None
    assert skip_reason(changed("web/package-lock.json")) == "lockfile"
    assert skip_reason(changed("go.sum")) == "lockfile"
    assert skip_reason(changed("static/app.min.js")) == "generated"
    assert skip_reason(changed("api/user_pb2.py")) == "generated"
    assert skip_reason(changed("vendor/lib/x.go")) == "generated"
    assert skip_reason(changed("src/vendors.py")) is None
    assert skip_reason(changed("old.py", status="removed")) == "removed"
    assert skip_reason(changed("logo.png", patch="")) == "binary or too large to diff"


def test_generator_markers_count_only_at_the_top_of_the_file():
    top = "@@ -0,0 +1,3 @@\n+// Code generated by mockgen. DO NOT EDIT.\n+package x\n+"
    assert skip_reason(changed("mock.go", "added", top)) == "generated"
    middle = "@@ -40,2 +40,3 @@\n x\n+# this is autogenerated\n y"
    assert skip_reason(changed("notes.py", patch=middle)) is None


def test_pick_files_keeps_order_and_caps_the_count():
    files = [changed("yarn.lock")] + [changed(f"f{i}.py") for i in range(4)]
    review, skipped = pick_files(files, limit=3)
    assert [f.path for f in review] == ["f0.py", "f1.py", "f2.py"]
    assert skipped == [("yarn.lock", "lockfile"), ("f3.py", "over the 3-file limit")]


def test_write_memo_sends_the_thread():
    class FakeAI:
        def ask(self, system, user, **kwargs):
            self.args = (system, user, kwargs)
            return "It adds retries."

    ai = FakeAI()
    assert write_memo(ai, "o/r", "Pull request #3: Add retries") == "It adds retries."
    system, user, kwargs = ai.args
    assert "o/r" in system and "memo" in system
    assert user == "Pull request #3: Add retries"
    assert kwargs == {"max_tokens": 300}


TWO_HUNKS = ("@@ -1,3 +1,3 @@\n import os\n-x = 1\n+x = 2\n y = 3\n"
             "@@ -20,2 +20,3 @@\n def f():\n+    pass\n     return 1\n\\ No newline at end of file")


def test_hunks_give_new_side_ranges():
    assert hunks(TWO_HUNKS) == [Hunk(1, 3), Hunk(20, 22)]
    assert hunks("@@ -5,2 +4,0 @@\n-a\n-b") == []
    assert hunks("@@ -1 +1 @@\n-a\n+b") == [Hunk(1, 1)]


def test_numbered_marks_new_side_lines():
    lines = numbered(TWO_HUNKS).splitlines()
    assert lines[0] == "@@ -1,3 +1,3 @@"
    assert lines[1] == "     1  import os"
    assert lines[2] == "       -x = 1"
    assert lines[3] == "     2 +x = 2"
    assert lines[4] == "     3  y = 3"
    assert lines[-1] == "    22      return 1"


def test_parse_findings_reads_a_fenced_json_array():
    answer = ('Here you go:\n```json\n[{"start": 2, "end": 2, "original": "x = 2\\n", '
              '"replacement": "x = 3", "note": "Off by one."}]\n```')
    assert parse_findings("a.py", answer) == [Suggestion("a.py", 2, 2, "x = 2", "x = 3", "Off by one.")]


def test_parse_findings_drops_bad_items():
    answer = """[
        {"start": 3, "original": "y", "replacement": ""},
        {"start": 0, "end": 1, "original": "a", "replacement": "b"},
        {"start": 5, "end": 4, "original": "a", "replacement": "b"},
        {"start": true, "end": 1, "original": "a", "replacement": "b"},
        {"start": "2", "original": "a", "replacement": "b"},
        {"start": 2, "replacement": "b"},
        "not an object"
    ]"""
    assert parse_findings("a.py", answer) == [Suggestion("a.py", 3, 3, "y", "", "")]
    assert parse_findings("a.py", "Looks good to me!") == []
    assert parse_findings("a.py", "[not json]") == []
    assert parse_findings("a.py", '{"start": 1}') == []


class ScriptedAI:
    def __init__(self, answers):
        self.answers = answers
        self.prompts = []

    def ask(self, system, user, **kwargs):
        self.prompts.append((system, user, kwargs))
        path = user.split("File: ")[1].split("\n")[0]
        answer = self.answers[path]
        if isinstance(answer, Exception):
            raise answer
        return answer


def test_review_file_sends_the_memo_and_numbered_diff():
    ai = ScriptedAI({"a.py": '[{"start": 2, "original": "x = 2", "replacement": "x = 3"}]'})
    result = review_file(ai, "o/r", "It bumps x.", changed("a.py", patch=TWO_HUNKS))
    assert result == FileReview("a.py", [Suggestion("a.py", 2, 2, "x = 2", "x = 3", "")])
    system, user, kwargs = ai.prompts[0]
    assert "o/r" in system and "JSON array" in system
    assert user.startswith("What the PR is for: It bumps x.\n\nFile: a.py\n\n@@ -1,3")
    assert "     2 +x = 2" in user
    assert kwargs == {"max_tokens": 1200}


def test_a_model_error_marks_only_that_file():
    ai = ScriptedAI({"a.py": "[]", "b.py": AIError("the model took too long to answer")})
    results = review_files(ai, "o/r", "memo", [changed("a.py"), changed("b.py")])
    assert results == [FileReview("a.py", []),
                       FileReview("b.py", [], "the model took too long to answer")]


def test_review_files_runs_four_at_a_time_in_order():
    running, peak, lock = [0], [0], threading.Lock()

    class SlowAI:
        def ask(self, system, user, **kwargs):
            with lock:
                running[0] += 1
                peak[0] = max(peak[0], running[0])
            time.sleep(0.02)
            with lock:
                running[0] -= 1
            return "[]"

    files = [changed(f"f{i}.py") for i in range(10)]
    results = review_files(SlowAI(), "o/r", "memo", files)
    assert [r.path for r in results] == [f.path for f in files]
    assert 1 < peak[0] <= 4
    assert review_files(SlowAI(), "o/r", "memo", []) == []


FILE = ["import os", "x = 2", "y = 3  "] + [""] * 16 + ["def f():", "    pass", "    return 1"]
FILE_HUNKS = [Hunk(1, 3), Hunk(20, 22)]


def suggestion(start, end, original, replacement="z = 0", path="a.py"):
    return Suggestion(path, start, end, original, replacement, "")


def test_check_accepts_a_suggestion_that_matches_the_file():
    assert check(suggestion(2, 3, "x = 2\ny = 3"), FILE, FILE_HUNKS) is None
    assert check(suggestion(21, 21, "    pass", ""), FILE, FILE_HUNKS) is None


def test_check_drops_suggestions_that_dont_apply():
    assert check(suggestion(10, 10, ""), FILE, FILE_HUNKS) == "outside the diff"
    assert check(suggestion(3, 20, "y = 3"), FILE, FILE_HUNKS) == "outside the diff"
    assert check(suggestion(22, 22, "x"), FILE[:21], FILE_HUNKS) == "past the end of the file"
    assert check(suggestion(2, 2, "x = 1"), FILE, FILE_HUNKS) == "doesn't match the file"
    assert check(suggestion(2, 3, "x = 2"), FILE, FILE_HUNKS) == "doesn't match the file"
    assert check(suggestion(2, 2, "x = 2", "x = 2  "), FILE, FILE_HUNKS) == "changes nothing"
    assert (check(suggestion(2, 2, "x = 2", "```\nx"), FILE, FILE_HUNKS)
            == "can't be shown as a suggestion")


class FileGitHub:
    def __init__(self, files):
        self.files = files
        self.reads = []

    def fetch_file(self, repo, path, ref=None):
        self.reads.append((repo, path, ref))
        content = self.files.get(path)
        if isinstance(content, Exception):
            raise content
        return content


def test_verify_reads_each_file_once_at_the_head_commit():
    gh = FileGitHub({"a.py": "\n".join(FILE) + "\n", "b.py": GitHubError(500, "oops")})
    files = [changed("a.py", patch=TWO_HUNKS), changed("b.py", patch=TWO_HUNKS),
             changed("c.py", patch=TWO_HUNKS)]
    good = suggestion(2, 2, "x = 2")
    found = [good, suggestion(2, 2, "x = 9"), suggestion(2, 2, "x = 2", path="b.py"),
             suggestion(2, 2, "x = 2", path="c.py")]
    assert verify(gh, "o/r", "abc", files, found) == ([good], 3)
    assert gh.reads == [("o/r", "a.py", "abc"), ("o/r", "b.py", "abc"), ("o/r", "c.py", "abc")]
