from tidebot.review import ChangedFile, pick_files, skip_reason, write_memo

PATCH = "@@ -1,2 +1,3 @@\n import os\n+import sys\n x = 1"


def changed(path, status="modified", patch=PATCH):
    return ChangedFile(path, status, patch)


def test_from_api_reads_the_github_entry():
    f = ChangedFile.from_api({"filename": "a.py", "status": "added", "patch": PATCH})
    assert f == ChangedFile("a.py", "added", PATCH)
    assert ChangedFile.from_api({"filename": "logo.png"}).patch == ""


def test_lockfiles_and_generated_code_are_skipped():
    assert skip_reason(changed("app/main.py")) is None
    assert skip_reason(changed("web/package-lock.json")) == "lockfile"
    assert skip_reason(changed("go.sum")) == "lockfile"
    assert skip_reason(changed("static/app.min.js")) == "generated"
    assert skip_reason(changed("api/user_pb2.py")) == "generated"
    assert skip_reason(changed("vendor/lib/x.go")) == "generated"
    assert skip_reason(changed("src/vendors.py")) is None
    assert skip_reason(changed("old.py", status="removed")) == "removed"
    assert skip_reason(changed("logo.png", patch="")) == "binary or too large to diff"


def test_generator_markers_count_only_at_the_top_of_the_file():
    top = "@@ -0,0 +1,3 @@\n+// Code generated by mockgen. DO NOT EDIT.\n+package x\n+"
    assert skip_reason(changed("mock.go", "added", top)) == "generated"
    middle = "@@ -40,2 +40,3 @@\n x\n+# this is autogenerated\n y"
    assert skip_reason(changed("notes.py", patch=middle)) is None


def test_pick_files_keeps_order_and_caps_the_count():
    files = [changed("yarn.lock")] + [changed(f"f{i}.py") for i in range(4)]
    review, skipped = pick_files(files, limit=3)
    assert [f.path for f in review] == ["f0.py", "f1.py", "f2.py"]
    assert skipped == [("yarn.lock", "lockfile"), ("f3.py", "over the 3-file limit")]


def test_write_memo_sends_the_thread():
    class FakeAI:
        def ask(self, system, user, **kwargs):
            self.args = (system, user, kwargs)
            return "It adds retries."

    ai = FakeAI()
    assert write_memo(ai, "o/r", "Pull request #3: Add retries") == "It adds retries."
    system, user, kwargs = ai.args
    assert "o/r" in system and "memo" in system
    assert user == "Pull request #3: Add retries"
    assert kwargs == {"max_tokens": 300}
